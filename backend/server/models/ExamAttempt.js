import mongoose from "mongoose";


// ======================================================
// Answer Schema
// ======================================================

const answerSchema = new mongoose.Schema(
  {
    questionId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Question",
      required: true,
    },

    // اختيار متعدد / صح وغلط / Checkbox
    selectedAnswers: [
      {
        type: Number,
      },
    ],

    // إجابة مقالية
    essayAnswer: {
      type: String,
      default: "",
    },

    // هل الإجابة صحيحة
    isCorrect: {
      type: Boolean,
      default: false,
    },

    // الدرجة المكتسبة
    marksAwarded: {
      type: Number,
      default: 0,
    },

    // هل تم مراجعة السؤال المقالي؟
    reviewed: {
      type: Boolean,
      default: false,
    },

    // تعليق المدرس
    teacherComment: {
      type: String,
      default: "",
    },
  },
  {
    _id: false,
  }
);


// ======================================================
// Exam Attempt Schema
// ======================================================

const examAttemptSchema = new mongoose.Schema(
  {
    // ==================================================
    // الطالب
    // ==================================================

    studentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },


    // ==================================================
    // الامتحان
    // ==================================================

    examId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Exam",
      required: true,
    },


    // ==================================================
    // رقم المحاولة
    // ==================================================

    attemptNumber: {
      type: Number,
      default: 1,
    },


    // ==================================================
    // الإجابات
    // ==================================================

    answers: {
      type: [answerSchema],
      default: [],
    },


    // ==================================================
    // ترتيب الأسئلة والاختيارات
    // ==================================================

    questionOrder: [
      {
        questionId: {
          type: mongoose.Schema.Types.ObjectId,
          ref: "Question",
        },

        optionsOrder: [
          {
            type: Number,
          },
        ],
      },
    ],


    // ==================================================
    // الدرجة النهائية
    // ==================================================

    score: {
      type: Number,
      default: 0,
    },


    // ==================================================
    // النسبة المئوية
    // ==================================================

    percentage: {
      type: Number,
      default: 0,
    },


    // ==================================================
    // حالة الامتحان
    // ==================================================

    status: {
      type: String,

      enum: [
        "in_progress",
        "paused",
        "submitted",
        "reviewed",
      ],

      default: "in_progress",
    },


    // ==================================================
    // وقت بداية الامتحان
    // ==================================================

    startedAt: {
      type: Date,
      default: Date.now,
    },


    // ==================================================
    // وقت انتهاء المحاولة الحالية
    //
    // مهم:
    // أثناء Pause يتم إلغاء الاعتماد عليه.
    // عند Resume يتم إعادة حسابه.
    // ==================================================

    expiresAt: {
      type: Date,
      default: null,
    },


    // ==================================================
    // عدد الثواني المتبقية
    //
    // ده أهم حقل في نظام الـ Pause
    // ==================================================

    remainingTime: {
      type: Number,
      default: 0,
      min: 0,
    },


    // ==================================================
    // وقت الـ Pause
    // ==================================================

    pausedAt: {
      type: Date,
      default: null,
    },


    // ==================================================
    // وقت التسليم النهائي
    // ==================================================

    finishedAt: {
      type: Date,
      default: null,
    },


    // ==================================================
    // الوقت المستغرق بالثواني
    // ==================================================

    timeTaken: {
      type: Number,
      default: 0,
    },


    // ==================================================
    // هل تم التسليم تلقائيًا؟
    // ==================================================

    isAutoSubmitted: {
      type: Boolean,
      default: false,
    },


    // ==================================================
    // من قام بمراجعة الأسئلة المقالية
    // ==================================================

    reviewedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },


    // ==================================================
    // وقت المراجعة
    // ==================================================

    reviewedAt: {
      type: Date,
      default: null,
    },


    // ==================================================
    // تعليق المدرس
    // ==================================================

    feedback: {
      type: String,
      default: "",
    },
  },
  {
    timestamps: true,
  }
);


// ======================================================
// Index
// ======================================================

examAttemptSchema.index({
  studentId: 1,
  examId: 1,
  status: 1,
});


// ======================================================
// Export
// ======================================================

export default mongoose.model(
  "ExamAttempt",
  examAttemptSchema
);